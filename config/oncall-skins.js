/**
 * On-Call demo customer skins.
 *
 * A skin generates ONE customer-branded product page for a specific prospect
 * without touching any mechanics. /oncall/c/<slug> serves the skin's chosen
 * vertical page (skin.vertical) rebranded with the customer's name, mark, and
 * theme, with the on-call shim active — that single URL is what a DE shares.
 * The generic /oncall hub itself is never
 * skinned. Adding a customer = adding one entry here.
 *
 * Two separate theme keys, one per surface: page.theme themes the stock
 * vertical page served through the brand shim, while the top-level theme
 * themes skinned surfaces other than the page. For stock-page skins without
 * page.file, the top-level theme falls back into the page shim too, so a
 * stock-page skin needs just one theme block. A natively branded page keeps
 * its own palette and is never overridden by the console theme; set page.theme
 * only when the page needs different variables from the console.
 *
 * Slugs are anonymous 8-char hex ids (generate with `openssl rand -hex 4`),
 * never the customer's name, so shared URLs don't leak who a demo is for.
 * Customer names appear only in rendered copy values, not in slugs, keys,
 * identifiers, or comments.
 *
 * What we deliberately do NOT personalize: telemetry service names, monitor
 * queries' service tags, and repo references in Slack investigation copy —
 * the responder investigates the repo that REPO_URL (app/services/oncall.js)
 * points at, so those must stay truthful for the investigation to be
 * believable.
 *
 * A skin may set devinSession: { auto: true, orgId, userId, apiKey } to have
 * its own alerts create a Devin investigation session immediately and reply
 * with the session link in the alert thread. Alerts raised from the generic
 * hub, or from skins without this key, stay alert-only. orgId defaults to
 * DEVIN_ORG_ID and the credential to DEVIN_ONCALL_SERVICE_KEY /
 * DEVIN_SERVICE_KEY / DEVIN_API_KEY; never put a credential in this file.
 *
 * A skin may set sonarPR: { auto: true, customer } to have each of its alerts
 * also open the SonarCloud remediation demo PR (app/services/sonar-pr-trigger.js)
 * in that customer's configured target repo, the same way the legacy
 * event-driven alert flow does. customer defaults to 'default'; the GitHub
 * token comes from the environment.
 *
 * A skin may set alertCard: { title, service, endpointLabel, release, team,
 * metricQuery, symptom, impact } to replace the matching display text on its
 * #oncall-alerts card (title is the monitor line, team the owner's team).
 * Each field is optional and falls back to the vertical's text; the
 * investigation session prompt keeps the vertical's real endpoint. Keep it
 * metric-shaped and free of the company name.
 *
 * A skin may set teamsAlerts: true to also post its alert card to the
 * Microsoft Teams channel behind ONCALL_TEAMS_WEBHOOK_URL. Other skins and
 * skinless alerts stay Slack-only even when that webhook is configured,
 * unless ONCALL_TEAMS_ALL_ALERTS=true.
 *
 * A skin may set hideRibbon: true to suppress the floating demo ribbon and its
 * collapsed dot; rerouting and alert posting are unaffected.
 *
 * A native page whose primary action has no legacy /api/<vertical> endpoint
 * (only the on-call one) sets oncallOnly: true, so its direct /<page-slug>
 * URL is served with the shim instead of as a bare page whose action 404s.
 *
 * Skins are direct-URL only: the stock /oncall hub never lists customers,
 * and each skin is reachable solely by its own /oncall/c/<slug> URL.
 */

