function roundMoney(value) {
  return Math.round(value * 100) / 100;
}

function resolveFulfillmentBranch(account) {
  return FULFILLMENT_BRANCHES[account.branchCode];
}

function buildCartLine(account, product, item) {
  const branch = resolveFulfillmentBranch(account);

  return {
    cartItemId: `a0i${String(Date.now()).slice(-9)}`,
    sku: item.sku,
    name: product.name,
    quantity: item.quantity,
    subscriptionTerm: item.subscriptionTerm,
    engineSerialNumber: item.esn,
    unitPrice: product.unitPrice,
    lineTotal: roundMoney(product.unitPrice * item.quantity),
    sapPlant: branch.sapPlant,
    storageLocation: branch.storageLocation,
    distributionCenter: branch.distributionCenter,
  };
}

function cartError(labelKey) {
  const error = new Error(LABELS[labelKey]);
  error.name = 'ValidationError';
  error.code = labelKey;
  error.statusCode = 400;
  return error;
}

function validateItem(product, item) {
  if (!product) throw cartError('Cart_Error_UnknownSKU');
  if (!Number.isInteger(item.quantity) || item.quantity <= 0) throw cartError('Cart_Error_InvalidQuantity');
  if (item.quantity > MAX_QUANTITY) throw cartError('Cart_Error_AboveMaximumQuantity');
  if (product.subscriptionTerms && !product.subscriptionTerms.includes(item.subscriptionTerm)) {
    throw cartError('Cart_Error_InvalidSubscriptionTerm');
  }
  if (product.esnRequired) {
    if (!item.esn) throw cartError('ESN_Required');
    if (!/^[0-9]{8}$/.test(item.esn)) throw cartError('ESN_Invalid_Format');
  }
}

async function addToCart(data) {
  const startTime = Date.now();
  const requestId = uuidv4();
  const account = DEALER_ACCOUNTS[data.username];
  if (!account) {
    const error = new Error(`Unknown storefront user: ${data.username || '(none)'}`);
    error.name = 'ValidationError';
    error.statusCode = 400;
    throw error;
  }

  const rawQuantity = data.quantity === undefined || data.quantity === null ? '1' : String(data.quantity).trim();
  const item = {
    sku: String(data.sku || '').trim(),
    quantity: rawQuantity === '' ? NaN : Number(rawQuantity),
    subscriptionTerm: data.subscriptionTerm ? Number(data.subscriptionTerm) : null,
    esn: data.esn ? String(data.esn).trim() : null,
  };
  const product = CATALOG[item.sku];
  validateItem(product, item);

  const context = {
    requestId,
    accountId: account.accountId,
    branchCode: account.branchCode,
    contractId: account.contractId,
    cartId: account.cartId,
    sku: item.sku,
    quantity: item.quantity,
    subscriptionTerm: item.subscriptionTerm,
  };

  logger.info('Adding item to OneMarket cart', { ...context, service: SERVICE, route: ROUTE });

  try {
    const line = buildCartLine(account, product, item);
    const duration = Date.now() - startTime;

    incrementMetric('onemarket_cart.add.success', { route: ROUTE, branchCode: account.branchCode });
    recordTiming('onemarket_cart.add.latency', duration, { route: ROUTE });

    return { success: true, cartId: account.cartId, line, requestId };
  } catch (error) {
    const duration = Date.now() - startTime;

    incrementMetric('onemarket_cart.add.failure', {
      route: ROUTE,
      errorClass: error.name,
      branchCode: account.branchCode,
    });
    recordTiming('onemarket_cart.add.latency', duration, { route: ROUTE, error: 'true' });

    logger.error('OneMarket add to cart failed', {
      ...context,
      error: error.message,
      errorClass: error.name,
      durationMs: duration,
      service: SERVICE,
    });

    Sentry.captureException(error, {
      tags: { route: ROUTE, service: SERVICE, branchCode: account.branchCode, alert_path: 'instant' },
      extra: context,
    });

    createSessionAndAlert({
      issueTitle: `${error.name}: ${error.message}`,
      issueUrl: `https://${process.env.SENTRY_ORG_SLUG || 'sentry-org'}.sentry.io/issues/?project=${process.env.SENTRY_PROJECT_ID || ''}&query=${encodeURIComponent(SENTRY_ISSUE_QUERY)}`,
      culprit: 'app/services/verticals/8d3527ab.js — buildCartLine',
      errorType: error.name || 'Error',
      errorValue: error.message,
      service: SERVICE,
      verticalLabel: 'Cummins OneMarket — Add to Cart',
      customer: '8d3527ab',
      slackMemberId: data.devinEmail ? '' : ONEMARKET_SLACK_MEMBER_ID,
      slackMemberIdFallback: ONEMARKET_SLACK_MEMBER_ID,
      devinUserId: data.devinUserId,
      devinEmail: data.devinEmail,
      devinOrgId: data.devinOrgId,
      promptAppendix: REMEDIATION_DIRECTIVE,
      tags: [
        { key: 'route', value: ROUTE },
        { key: 'service', value: SERVICE },
        { key: 'branchCode', value: account.branchCode },
        { key: 'sku', value: item.sku },
      ],
      extra: context,
      level: 'error',
      platform: 'node',
      firstSeen: '',
      lastSeen: new Date().toISOString(),
      count: '',
      shortId: '',
      project: 'event-driven-devin',
      release: process.env.SENTRY_RELEASE || `${SERVICE}@1.0.0`,
      environment: process.env.DD_ENV || 'prod',
      triggeredRule: '',
    }).catch((alertError) => {
      logger.error('Failed to create Devin session for OneMarket cart error', {
        requestId,
        error: alertError.message,
      });
    });

    error.requestId = requestId;
    throw error;
  }
}

